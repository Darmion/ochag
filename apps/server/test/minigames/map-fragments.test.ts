import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildApp } from '../../src/app.ts';
import { createTestDatabase } from '../helpers.ts';
test('map fragments API: shared edits, private answer, permission and revision guards', async t => {
  const { pg, db } = await createTestDatabase(); const app = await buildApp(db, { rateMax: 10000 });
  t.after(async () => { await app.close(); await pg.close(); });
  const req = (method: any, url: string, token?: string, payload?: any) => app.inject({ method, url, ...(token ? { headers: { authorization: `Bearer ${token}` } } : {}), ...(payload ? { payload } : {}) });
  const register = async (username: string) => (await req('POST', '/auth/register', undefined, { username, password: 'x' })).json();
  const gm = await register('fragments_gm'), guest = await register('fragments_guest'), outsider = await register('fragments_out');
  const campaign = (await req('POST', '/campaigns', gm.token, { name: 'Fragments' })).json().id;
  const invite = (await req('POST', `/campaigns/${campaign}/invites`, gm.token)).json().code;
  await req('POST', '/campaigns/join', guest.token, { code: invite });
  const path = `/campaigns/${campaign}/minigames/map-fragments`, create = { action: 'create', story: 0, revision: 0 };
  assert.equal((await req('GET', path)).statusCode, 401);
  assert.equal((await req('GET', path, outsider.token)).statusCode, 404);
  assert.equal((await req('POST', path, outsider.token, create)).statusCode, 404);
  assert.equal((await req('POST', path, guest.token, create)).statusCode, 403);
  const created = await req('POST', path, gm.token, create); assert.equal(created.statusCode, 200, created.body);
  assert.deepEqual(created.json().game.solution, [1, 0, 2, 3]);
  const publicResult = (await req('GET', path, guest.token)).json();
  assert.equal(publicResult.stories.length, 3); assert.equal('solution' in publicResult.stories[0], false);
  let game = publicResult.game;
  assert.equal('solution' in game, false); assert.equal('hint' in game, false);
  for (const action of ['hint', 'solve', 'cancel']) assert.equal((await req('POST', path, guest.token, { action, revision: game.revision })).statusCode, 403);
  const append = { action: 'append', place: 1, revision: game.revision };
  const concurrent = await Promise.all([req('POST', path, guest.token, append), req('POST', path, guest.token, append)]);
  assert.deepEqual(concurrent.map(r => r.statusCode).sort(), [200, 409]);
  game = (await req('GET', path, guest.token)).json().game;
  assert.deepEqual(game.route, [1]); assert.equal(game.attempts, 0);
  game = (await req('POST', path, guest.token, { action: 'note', text: 'Мельница затоплена.', revision: game.revision })).json().game;
  assert.equal(game.notes[0].text, 'Мельница затоплена.'); assert.equal('solution' in game, false);
  assert.equal((await req('POST', path, guest.token, { action: 'check', solution: [1, 0, 2, 3], revision: game.revision })).statusCode, 400);
  game = (await req('POST', path, gm.token, { action: 'hint', revision: game.revision })).json().game;
  assert.ok((await req('GET', path, guest.token)).json().game.hint);
  for (const place of [0, 2, 3]) game = (await req('POST', path, guest.token, { action: 'append', place, revision: game.revision })).json().game;
  game = (await req('POST', path, guest.token, { action: 'check', revision: game.revision })).json().game;
  assert.equal(game.phase, 'solved'); assert.equal('solution' in game, false);
  assert.equal((await req('POST', path, gm.token, create)).statusCode, 409);
  assert.equal((await req('POST', path, gm.token, { ...create, revision: game.revision })).statusCode, 200);
  const other = (await req('POST', '/campaigns', gm.token, { name: 'Other' })).json().id;
  assert.equal((await req('GET', `/campaigns/${other}/minigames/map-fragments`, gm.token)).json().game, null);
});
