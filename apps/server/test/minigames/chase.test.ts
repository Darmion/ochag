import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildApp } from '../../src/app.ts';
import { createTestDatabase } from '../helpers.ts';
test('chase API: membership, shared stages, replay guards and server-only dice', async t => {
  const { pg, db } = await createTestDatabase(); const app = await buildApp(db, { rateMax: 10000 });
  t.after(async () => { await app.close(); await pg.close(); });
  const req = (method: any, url: string, token?: string, payload?: any) => app.inject({ method, url, ...(token ? { headers: { authorization: `Bearer ${token}` } } : {}), ...(payload ? { payload } : {}) });
  const register = async (username: string) => (await req('POST', '/auth/register', undefined, { username, password: 'x' })).json();
  const gm = await register('chase_gm'), guest = await register('chase_guest'), stranger = await register('chase_stranger');
  const campaign = (await req('POST', '/campaigns', gm.token, { name: 'Chase' })).json().id;
  const invite = (await req('POST', `/campaigns/${campaign}/invites`, gm.token)).json().code;
  await req('POST', '/campaigns/join', guest.token, { code: invite });
  const path = `/campaigns/${campaign}/minigames/chase`, create = { action: 'create', revision: 0 };
  assert.equal((await req('GET', path)).statusCode, 401);
  assert.equal((await req('GET', path, stranger.token)).statusCode, 404);
  assert.equal((await req('POST', path, stranger.token, create)).statusCode, 404);
  assert.equal((await req('POST', path, guest.token, create)).statusCode, 403);
  const response = await req('POST', path, gm.token, create);
  assert.equal(response.statusCode, 200, response.body); let game = response.json().game;
  assert.equal((await req('POST', path, guest.token, { action: 'hide', revision: game.revision })).statusCode, 409);
  const pick = { action: 'route', route: 1, revision: game.revision };
  const selections = await Promise.all([req('POST', path, guest.token, pick), req('POST', path, guest.token, pick)]);
  assert.deepEqual(selections.map(r => r.statusCode).sort(), [200, 409]);
  game = (await req('GET', path, guest.token)).json().game;
  assert.equal(game.phase, 'obstacle'); assert.equal(game.turn, 0);
  assert.equal((await req('POST', path, guest.token, { action: 'route', route: 0, revision: game.revision })).statusCode, 409);
  assert.equal((await req('POST', path, guest.token, { action: 'hide', die: 6, revision: game.revision })).statusCode, 400);
  const advance = { action: 'hide', revision: game.revision };
  const outcomes = await Promise.all([req('POST', path, guest.token, advance), req('POST', path, guest.token, advance)]);
  assert.deepEqual(outcomes.map(r => r.statusCode).sort(), [200, 409]);
  game = (await req('GET', path, guest.token)).json().game;
  assert.equal(game.turn, 1); assert.ok(game.lastRoll >= 1 && game.lastRoll <= 6);
  assert.equal((await req('POST', path, guest.token, { action: 'cancel', revision: game.revision })).statusCode, 403);
  game = (await req('POST', path, gm.token, { action: 'cancel', revision: game.revision })).json().game;
  assert.equal(game.phase, 'cancelled');
  assert.equal((await req('POST', path, gm.token, create)).statusCode, 409);
  assert.equal((await req('POST', path, gm.token, { ...create, revision: game.revision })).statusCode, 200);
  const other = (await req('POST', '/campaigns', gm.token, { name: 'Other' })).json().id;
  assert.equal((await req('GET', `/campaigns/${other}/minigames/chase`, gm.token)).json().game, null);
});
