import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildApp } from '../../src/app.ts';
import { createTestDatabase } from '../helpers.ts';
test('alchemy API: authorization, shared inventory, concurrency, recipe and terminal state', async t => {
  const { pg, db } = await createTestDatabase();
  const app = await buildApp(db, { rateMax: 10000 });
  t.after(async () => { await app.close(); await pg.close(); });
  const req = (method: any, url: string, token?: string, payload?: any) => app.inject({ method, url, ...(token ? { headers: { authorization: `Bearer ${token}` } } : {}), ...(payload ? { payload } : {}) });
  const register = async (username: string) => (await req('POST', '/auth/register', undefined, { username, password: 'x' })).json();
  const gm = await register('alch_gm'), guest = await register('alch_guest'), stranger = await register('alch_stranger');
  const campaign = (await req('POST', '/campaigns', gm.token, { name: 'Alchemy' })).json().id;
  const invite = (await req('POST', `/campaigns/${campaign}/invites`, gm.token)).json().code;
  await req('POST', '/campaigns/join', guest.token, { code: invite });
  const path = `/campaigns/${campaign}/minigames/alchemy`;
  assert.equal((await req('GET', path)).statusCode, 401);
  assert.equal((await req('GET', path, stranger.token)).statusCode, 404);
  const create = { action: 'create', recipe: 0, limit: 8, revision: 0 };
  assert.equal((await req('POST', path, stranger.token, create)).statusCode, 404);
  assert.equal((await req('POST', path, guest.token, create)).statusCode, 403);
  assert.equal((await req('POST', path, gm.token, { ...create, recipe: 8 })).statusCode, 400);
  let response = await req('POST', path, gm.token, create);
  assert.equal(response.statusCode, 200, response.body);
  let game = response.json().game;
  const add = { action: 'add', ingredient: 2, revision: game.revision };
  const results = await Promise.all([req('POST', path, guest.token, add), req('POST', path, guest.token, add)]);
  assert.deepEqual(results.map(r => r.statusCode).sort(), [200, 409]);
  game = (await req('GET', path, guest.token)).json().game;
  assert.equal(game.stock[2], 1); assert.equal(game.moves, 1);
  assert.equal((await req('POST', path, guest.token, { action: 'cancel', revision: game.revision })).statusCode, 403);
  assert.equal((await req('POST', path, guest.token, { action: 'heat', revision: game.revision, essence: 5 })).statusCode, 400);
  for (const ingredient of [2, 0]) game = (await req('POST', path, guest.token, { action: 'add', ingredient, revision: game.revision })).json().game;
  game = (await req('POST', path, guest.token, { action: 'bottle', revision: game.revision })).json().game;
  assert.equal(game.phase, 'perfect');
  assert.equal((await req('POST', path, guest.token, { action: 'heat', revision: game.revision })).statusCode, 409);
  assert.equal((await req('POST', path, gm.token, create)).statusCode, 409);
  response = await req('POST', path, gm.token, { ...create, revision: game.revision });
  assert.equal(response.statusCode, 200);
  game = response.json().game;
  assert.equal((await req('POST', path, gm.token, { action: 'cancel', revision: game.revision })).json().game.phase, 'cancelled');
  const other = (await req('POST', '/campaigns', gm.token, { name: 'Other' })).json().id;
  assert.equal((await req('GET', `/campaigns/${other}/minigames/alchemy`, gm.token)).json().game, null);
});
