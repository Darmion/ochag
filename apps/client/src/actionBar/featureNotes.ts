  if (id === 'purity-of-body') return 'Само: урон ядом и «отравлен».';
  if (id === 'lucky') return 'Само: единица на к20 атаки, проверки, спасброска перебрасывается.';
  if (id === 'brave') return 'Само: преимущество к спасброскам против испуга.';
  if (id === 'fey-ancestry') return 'Само: преимущество к спасброскам против очарования; «Усыпление» не действует.';
  if (id === 'dwarven-resilience') return 'Само: преимущество к спасброскам против яда.';
  if (id === 'gnome-cunning') return 'Само: преимущество к спасброскам ИНТ, МДР и ХАР против магии.';
