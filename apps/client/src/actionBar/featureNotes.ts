  if (id === 'blessed-healer') return 'Само: лечите другого — лечитесь и сами.';
  if (id === 'empowered-evocation') return 'Само: «Огненный шар», «Волшебная стрела» и другие воплощения.';
  if (id === 'mindless-rage') return 'Само: в ярости очарование и испуг не ложатся, прежние ждут её конца.';
