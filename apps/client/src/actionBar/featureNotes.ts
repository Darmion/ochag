  if (id === 'dark-ones-own-luck') return 'Само: спасброски и проверки против СЛ, что бросает сервер.';
  if (id === 'divine-strike') return 'Само: первое попадание оружием в ваш ход.';
  if (id === 'aura-of-courage') return 'Само: испуг не ложится на вас и союзников рядом.';
  if (id === 'improved-divine-smite') return 'Само: каждое попадание рукопашным оружием.';
  if (id === 'brutal-critical' || id === 'savage-attacks') return 'Само: критическое попадание рукопашным оружием.';
  if (id === 'relentless-rage') return 'Само: сервер бросит спасбросок, когда хиты упадут до 0.';
  if (id === 'relentless-endurance') return 'Само: первый раз до долгого отдыха хиты упадут до 1, а не до 0.';
