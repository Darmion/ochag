const CATALOG = new Map(CLASS_FEATURE_LIST.map(feature => [feature.id, feature.text]));

export function featureCard(title: string): FeatureCard | null {
  const entry = ENTRIES[title];
  if (!entry) return null;
  if (typeof entry !== 'string') return entry;
  const text = CATALOG.get(entry);
  return text ? { text, automation: 'auto' } : null;
}

export const FEATURE_TITLES = Object.keys(ENTRIES);

// Cards for what a level brings; a new class's first-level features come with the hero builder's own texts.
export function featureTextsFor(plan: LevelUpPlan): Record<string, { text: string; automation: FeatureAutomation | null }> {
  const firstLevel = plan.newClass && plan.classId ? SRD_CLASSES.find(entry => entry.id === plan.classId)?.features ?? [] : [];
  const texts: Record<string, { text: string; automation: FeatureAutomation | null }> = {};
  for (const title of [...plan.features, ...(plan.subclass?.srdFeatures ?? [])]) {
    const card = featureCard(title);
    const trait = firstLevel.find(([name]) => name === title);
    if (card) texts[title] = card;
    else if (trait) texts[title] = { text: trait[1], automation: null };
  }
  return texts;
}
