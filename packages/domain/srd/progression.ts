export type ResourceRule = { name: string; max: number; recharge: 'short' | 'long' };

export function classResources(classId: ClassId, level: number, mods: { charisma: number }, subclass?: string): ResourceRule[] {
  const list: ResourceRule[] = [];
  switch (classId) {
    case 'barbarian':
      if (level < 20) list.push({ name: 'Ярость', max: level >= 17 ? 6 : level >= 12 ? 5 : level >= 6 ? 4 : level >= 3 ? 3 : 2, recharge: 'long' });
      if (level >= 11) list.push({ name: 'Непреклонная ярость', max: 6, recharge: 'short' });
      break;
    case 'bard':
      list.push({ name: 'Вдохновение барда', max: Math.max(1, mods.charisma), recharge: level >= 5 ? 'short' : 'long' });
      break;
    case 'cleric':
      if (level >= 2) list.push({ name: 'Божественный канал', max: level >= 18 ? 3 : level >= 6 ? 2 : 1, recharge: 'short' });
      break;
    case 'druid':
      if (level >= 2) list.push({ name: 'Дикий облик', max: 2, recharge: 'short' });
      if (level >= 2 && subclass === 'land') list.push({ name: 'Природное восстановление', max: 1, recharge: 'long' });
      break;
    case 'fighter':
      list.push({ name: 'Второе дыхание', max: 1, recharge: 'short' });
      if (level >= 2) list.push({ name: 'Всплеск действий', max: level >= 17 ? 2 : 1, recharge: 'short' });
      if (level >= 9) list.push({ name: 'Упорный', max: level >= 17 ? 3 : level >= 13 ? 2 : 1, recharge: 'long' });
      if (level >= 3 && subclass === 'battle-master') list.push({ name: 'Кости превосходства', max: level >= 15 ? 6 : level >= 7 ? 5 : 4, recharge: 'short' });
      break;
    case 'rogue':
      if (level >= 20) list.push({ name: 'Удача', max: 1, recharge: 'short' });
      break;
    case 'monk':
      if (level >= 2) list.push({ name: 'Ци', max: level, recharge: 'short' });
      if (level >= 6 && subclass === 'open-hand') list.push({ name: 'Цельность тела', max: 1, recharge: 'long' });
      break;
    case 'paladin':
      list.push({ name: 'Божественное чувство', max: Math.max(1, 1 + mods.charisma), recharge: 'long' });
      list.push({ name: 'Наложение рук', max: 5 * level, recharge: 'long' });
      if (level >= 3) list.push({ name: 'Божественный канал', max: 1, recharge: 'short' });
      if (level >= 14) list.push({ name: 'Очищающее касание', max: Math.max(1, mods.charisma), recharge: 'long' });
      if (level >= 20 && subclass === 'devotion') list.push({ name: 'Святой нимб', max: 1, recharge: 'long' });
      break;
    case 'sorcerer':
      if (level >= 2) list.push({ name: 'Очки чародейства', max: level, recharge: 'long' });
      break;
    case 'warlock':
      if (level >= 6 && subclass === 'fiend') list.push({ name: 'Удача тёмного', max: 1, recharge: 'short' });
      if (level >= 14 && subclass === 'fiend') list.push({ name: 'Бросок через ад', max: 1, recharge: 'long' });
      if (level >= 20) list.push({ name: 'Мастер таинств', max: 1, recharge: 'long' });
      break;
    case 'wizard':
      list.push({ name: 'Арканное восстановление', max: 1, recharge: 'long' });
      break;
    default:
      break;
  }
  return list;
}

export function mergedClassResources(classes: Array<{ id: ClassId; level: number; subclass?: string }>, mods: { charisma: number }): ResourceRule[] {
  const byName = new Map<string, ResourceRule>();
  for (const entry of classes) {
    for (const rule of classResources(entry.id, entry.level, mods, entry.subclass)) {
      const known = byName.get(rule.name);
      byName.set(rule.name, known
        ? { name: rule.name, max: Math.max(known.max, rule.max), recharge: known.recharge === 'short' || rule.recharge === 'short' ? 'short' : 'long' }
        : rule);
    }
  }
  return [...byName.values()];
}
