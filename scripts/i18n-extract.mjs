import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CLIENT = join(ROOT, 'apps', 'client', 'src');
const KEYS_FILE = join(CLIENT, 'locales', 'keys.ts');
const ENGLISH_FILE = join(CLIENT, 'locales', 'en.json');

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== 'locales' && entry.name !== 'node_modules') files.push(...walk(path));
    } else if (/\.(vue|ts)$/.test(entry.name) && entry.name !== 'i18nCore.ts' && !entry.name.endsWith('.d.ts')) {
      files.push(path);
    }
  }
  return files;
}

const unescape = text => text.replace(/\\(['"`\\])/g, '$1').replace(/\\n/g, '\n');
const LITERAL = String.raw`(['"\x60])((?:\\.|(?!\1)[^\\])*)\1`;
const CALL = new RegExp(String.raw`(?<![\w.$])(?:t|tr)\(\s*` + LITERAL, 'g');
const PLURAL = new RegExp(String.raw`(?<![\w.$])tn\(\s*[^,()]+,\s*` + LITERAL, 'g');

export function collectKeyFiles(root = CLIENT) {
  const keys = new Map();
  for (const file of walk(root)) {
    const text = readFileSync(file, 'utf8');
    for (const pattern of [CALL, PLURAL]) {
      for (const match of text.matchAll(pattern)) {
        if (match[1] === '`' && match[2].includes('${')) continue;
        const key = unescape(match[2]);
        if (!key.trim()) continue;
        if (!keys.has(key)) keys.set(key, { file: relative(root, file).replace(/\\/g, '/'), at: match.index, plural: pattern === PLURAL });
      }
    }
  }
  return keys;
}

export function collectKeys(root = CLIENT) {
  return [...collectKeyFiles(root).keys()].sort((a, b) => a.localeCompare(b, 'ru'));
}

export function readEnglish() {
  return JSON.parse(readFileSync(ENGLISH_FILE, 'utf8'));
}

export function keysModule(keys) {
  return `// Generated by scripts/i18n-extract.mjs, do not edit (docs/I18N.md): every UI string passed to t(), tr() and tn().\nexport const SOURCE_KEYS: string[] = ${JSON.stringify(keys, null, 2)};\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const keys = collectKeys();
  const next = keysModule(keys);
  let current = '';
  try {
    current = readFileSync(KEYS_FILE, 'utf8');
  } catch {
  }
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('apps/client/src/locales/keys.ts устарел — запустите: npm run i18n:extract');
      process.exit(1);
    }
    console.log(`keys.ts свеж: ${keys.length} строк.`);
  } else {
    if (current !== next) writeFileSync(KEYS_FILE, next, 'utf8');
    const { collectStrings, englishStats, flattenLocaleFile, isTranslated, mergeEnglishFile, SERVER_ROOTS } = await import('./i18n-strings.mjs');
    const strings = collectStrings();
    for (const root of SERVER_ROOTS) {
      for (const [key, entry] of collectStrings(root)) {
        const known = strings.get(key);
        if (!known) strings.set(key, entry);
        else for (const file of entry.files) if (!known.files.includes(file)) known.files.push(file);
      }
    }
    for (const [key, { file, at, plural }] of collectKeyFiles()) {
      const entry = strings.get(key);
      if (!entry) strings.set(key, { files: [file], first: { file, at }, plural });
      else if (plural) entry.plural = true;
    }
    const previousText = existsSync(ENGLISH_FILE) ? readFileSync(ENGLISH_FILE, 'utf8') : '';
    const merged = mergeEnglishFile(previousText ? JSON.parse(previousText) : {}, strings);
    const mergedText = `${JSON.stringify(merged, null, 2)}\n`;
    if (mergedText !== previousText) writeFileSync(ENGLISH_FILE, mergedText, 'utf8');
    const en = flattenLocaleFile(merged);
    const missing = keys.filter(key => !isTranslated(en.get(key)));
    const stats = englishStats(merged);
    console.log(`Строк через t(): ${keys.length}, без английского: ${missing.length}.`);
    console.log(`en.json: всех строк интерфейса ${stats.total}, переведено ${stats.done}${mergedText !== previousText ? ' — файл обновлён' : ''}.`);
    for (const key of missing.slice(0, 60)) console.log(`  нет: ${JSON.stringify(key)}`);
    const { srdEnglish, SRD_ENGLISH_FILE } = await import('./i18n-srd.mjs');
    const srdText = `${JSON.stringify(await srdEnglish(), null, 1)}
`;
    if (!existsSync(SRD_ENGLISH_FILE) || readFileSync(SRD_ENGLISH_FILE, 'utf8') !== srdText) writeFileSync(SRD_ENGLISH_FILE, srdText, 'utf8');
  }
}
